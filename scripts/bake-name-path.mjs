// Bakes the outline of the name, in Zilla Slab Bold, into src/game/namepath.ts, so the scene extrudes plain
// numbers and never parses a font at run time. Run it again after changing NAME or the font:
//
//   node scripts/bake-name-path.mjs
//
// opentype.js reads WOFF but not WOFF2, hence the .woff file. The path is written y-up (a glyph stands on y = 0 and its
// top is at positive y), the way three.js expects shapes, with one subpath per contour.
import { readFileSync, writeFileSync } from "node:fs";
import opentype from "opentype.js";

const NAME = "Kevin Dong";
const FONT = new URL(
  "../node_modules/@fontsource/zilla-slab/files/zilla-slab-latin-700-normal.woff",
  import.meta.url
);
const OUT = new URL("../src/game/namepath.ts", import.meta.url);

const buffer = readFileSync(FONT);
const font = opentype.parse(buffer.buffer.slice(buffer.byteOffset, buffer.byteOffset + buffer.byteLength));
const SIZE = font.unitsPerEm; // 1 em = this many path units
const path = font.getPath(NAME, 0, 0, SIZE, { kerning: true });

const r = (n) => Math.round(n * 10) / 10;
const d = path.commands
  .map((c) => {
    const y = (v) => r(-v); // opentype is y-down: flip
    switch (c.type) {
      case "M":
        return `M${r(c.x)} ${y(c.y)}`;
      case "L":
        return `L${r(c.x)} ${y(c.y)}`;
      case "Q":
        return `Q${r(c.x1)} ${y(c.y1)} ${r(c.x)} ${y(c.y)}`;
      case "C":
        return `C${r(c.x1)} ${y(c.y1)} ${r(c.x2)} ${y(c.y2)} ${r(c.x)} ${y(c.y)}`;
      case "Z":
        return "Z";
    }
  })
  .join("");

const box = path.getBoundingBox();
const capHeight = font.tables.os2?.sCapHeight ?? SIZE * 0.68;

writeFileSync(
  OUT,
  `// Generated by scripts/bake-name-path.mjs: do not edit by hand.
// "${NAME}" in Zilla Slab Bold (kerned), y-up, ${SIZE} units to the em.

export const NAME_TEXT = ${JSON.stringify(NAME)};

/** The outline: M / L / Q / C / Z commands, one subpath per contour (letters and their counters). */
export const NAME_PATH =
  ${JSON.stringify(d)};

/** The outline's bounds, in the same units as NAME_PATH. */
export const NAME_BOX = { x0: ${r(box.x1)}, x1: ${r(box.x2)}, y0: ${r(-box.y2)}, y1: ${r(-box.y1)} };

/** Height of the capital letters, in the same units. */
export const NAME_CAP_HEIGHT = ${capHeight};
`
);
console.log(`wrote ${OUT.pathname}: ${d.length} chars, box`, box, "capHeight", capHeight);
