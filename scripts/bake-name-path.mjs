// Bakes the outlines of the name (and the "in" of the LinkedIn mark), in Goudy Bookletter 1911, into src/game/namepath.ts, so the scene cuts plain numbers
// and never parses a font at run time. Run it again after changing the texts or the font:
//
//   node scripts/bake-name-path.mjs
//
// opentype.js reads WOFF but not WOFF2, hence the .woff file. Paths are written y-up (a glyph stands on y = 0 and its top is
// at positive y), the way three.js expects shapes, with one subpath per contour.
import { readFileSync, writeFileSync } from "node:fs";
import opentype from "opentype.js";

const NAME = "Kevin Dong";
const LINKEDIN = "in"; // inside the LinkedIn badge
const FONT = new URL(
  "../node_modules/@fontsource/goudy-bookletter-1911/files/goudy-bookletter-1911-latin-400-normal.woff",
  import.meta.url
);
const OUT = new URL("../src/game/namepath.ts", import.meta.url);

const buffer = readFileSync(FONT);
const font = opentype.parse(buffer.buffer.slice(buffer.byteOffset, buffer.byteOffset + buffer.byteLength));
const SIZE = font.unitsPerEm; // 1 em = this many path units
const TRACKING = 0; // extra room between letters, in 1/1000 em (none: the name is raised and solid, so the letters can touch)
const r = (n) => Math.round(n * 10) / 10;

/** One string as { d, box }: the path data (kerned, y-up) and its bounds. */
function bake(text) {
  const path = font.getPath(text, 0, 0, SIZE, { kerning: true, tracking: TRACKING });
  const d = path.commands
    .map((c) => {
      const y = (v) => r(-v); // opentype is y-down: flip
      switch (c.type) {
        case "M":
          return `M${r(c.x)} ${y(c.y)}`;
        case "L":
          return `L${r(c.x)} ${y(c.y)}`;
        case "Q":
          return `Q${r(c.x1)} ${y(c.y1)} ${r(c.x)} ${y(c.y)}`;
        case "C":
          return `C${r(c.x1)} ${y(c.y1)} ${r(c.x2)} ${y(c.y2)} ${r(c.x)} ${y(c.y)}`;
        case "Z":
          return "Z";
      }
    })
    .join("");
  const b = path.getBoundingBox();
  return { d, box: `{ x0: ${r(b.x1)}, x1: ${r(b.x2)}, y0: ${r(-b.y2)}, y1: ${r(-b.y1)} }` };
}

const name = bake(NAME);
const linkedin = bake(LINKEDIN);
const capHeight = font.tables.os2?.sCapHeight ?? SIZE * 0.68;

writeFileSync(
  OUT,
  `// Generated by scripts/bake-name-path.mjs: do not edit by hand.
// Goudy Bookletter 1911 (kerned), y-up, ${SIZE} units to the em.

export const NAME_TEXT = ${JSON.stringify(NAME)};

/** The name's outline: M / L / Q / C / Z commands, one subpath per contour (letters and their counters). */
export const NAME_PATH =
  ${JSON.stringify(name.d)};

/** The outline's bounds, in the same units as NAME_PATH. */
export const NAME_BOX = ${name.box};

/** Height of the capital letters, in the same units. */
export const NAME_CAP_HEIGHT = ${capHeight};

/** "${LINKEDIN}", the letters inside the LinkedIn badge, and its bounds. */
export const IN_PATH =
  ${JSON.stringify(linkedin.d)};
export const IN_BOX = ${linkedin.box};
`
);
console.log(`wrote ${OUT.pathname}: name ${name.d.length} chars, "in" ${linkedin.d.length} chars`);
